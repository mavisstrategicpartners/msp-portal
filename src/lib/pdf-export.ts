import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";

export interface AttendanceRegisterDay {
  dateStr: string;
  dayName: "Mon" | "Tue" | "Wed" | "Thu" | "Fri";
  formattedDate: string;
  status: "Present" | "Approved Leave" | "Did Not Clock In" | "Upcoming";
  clockInTime?: string | null;
  clockOutTime?: string | null;
  hoursWorked?: string;
  leaveReason?: string;
}

export interface AttendanceRegisterRow {
  userId: string;
  name: string;
  email: string;
  role: string;
  department: string;
  tier: string;
  days: AttendanceRegisterDay[];
  daysPresent: number;
  daysLeave: number;
  daysAbsent: number;
  totalHoursWorked: string;
  complianceRate: number;
}

export interface AttendanceRegisterData {
  weekStart: string;
  weekEnd: string;
  weekLabel: string;
  schedule: string;
  rows: AttendanceRegisterRow[];
  stats: {
    totalStaff: number;
    avgAttendanceRate: number;
    totalHoursLogged: string;
    totalLeaveDays: number;
  };
}

export interface LiveStaffMember {
  id: string;
  name: string;
  email: string;
  role: string;
  department: string;
  tier: string;
  status: "Clocked In" | "On Break" | "Clocked Out";
  time: string;
  hours: string;
  currentProject?: string;
}

// 1. Export Live Workforce Presence to PDF
export function exportLivePresencePdf(
  staffList: LiveStaffMember[],
  meta?: { generatedBy?: string }
) {
  const doc = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: "a4",
  });

  const now = new Date();
  const dateStr = now.toLocaleDateString("en-ZA", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });
  const timeStr = now.toLocaleTimeString("en-ZA", {
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
  });

  // Primary brand palette (Mavis navy & emerald)
  const primaryColor = [15, 23, 42] as [number, number, number]; // Slate 900
  const emeraldColor = [16, 185, 129] as [number, number, number]; // Emerald 500
  const mutedTextColor = [100, 116, 139] as [number, number, number]; // Slate 500

  // Header Title
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.setTextColor(...primaryColor);
  doc.text("MAVIS STRATEGIC PARTNERS", 14, 18);

  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.setTextColor(...emeraldColor);
  doc.text("LIVE WORKFORCE PRESENCE REPORT", 14, 25);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(...mutedTextColor);
  doc.text(`Generated: ${dateStr} at ${timeStr} SAST`, 14, 31);
  if (meta?.generatedBy) {
    doc.text(`Generated by: ${meta.generatedBy}`, 14, 36);
  }

  // Summary Cards
  const total = staffList.length;
  const clockedIn = staffList.filter((s) => s.status === "Clocked In").length;
  const onBreak = staffList.filter((s) => s.status === "On Break").length;
  const clockedOut = staffList.filter((s) => s.status === "Clocked Out").length;
  const activeRate = Math.round(((clockedIn + onBreak) / (total || 1)) * 100);

  const startY = meta?.generatedBy ? 42 : 37;

  // Background box for metrics
  doc.setFillColor(248, 250, 252);
  doc.setDrawColor(226, 232, 240);
  doc.roundedRect(14, startY, 182, 18, 2, 2, "FD");

  doc.setFontSize(8);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(...mutedTextColor);

  doc.text("TOTAL STAFF", 20, startY + 6);
  doc.text("CLOCKED IN (WORKING)", 60, startY + 6);
  doc.text("ON BREAK", 115, startY + 6);
  doc.text("CLOCKED OUT", 155, startY + 6);

  doc.setFontSize(13);
  doc.setTextColor(...primaryColor);
  doc.text(`${total}`, 20, startY + 14);

  doc.setTextColor(5, 150, 105); // Emerald 600
  doc.text(`${clockedIn} (${activeRate}%)`, 60, startY + 14);

  doc.setTextColor(217, 119, 6); // Amber 600
  doc.text(`${onBreak}`, 115, startY + 14);

  doc.setTextColor(...mutedTextColor);
  doc.text(`${clockedOut}`, 155, startY + 14);

  // Staff Table
  const tableData = staffList.map((s, idx) => [
    (idx + 1).toString(),
    s.name,
    s.department,
    s.role,
    s.status,
    s.time || "—",
    s.hours || "0h 0m",
  ]);

  autoTable(doc, {
    startY: startY + 23,
    head: [["#", "Staff Member", "Department", "Role / Title", "Current Status", "Clocked In", "Hours Worked"]],
    body: tableData,
    theme: "grid",
    headStyles: {
      fillColor: primaryColor,
      textColor: [255, 255, 255],
      fontSize: 8.5,
      fontStyle: "bold",
      halign: "left",
    },
    bodyStyles: {
      fontSize: 8,
      textColor: [30, 41, 59],
      cellPadding: 2.5,
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252],
    },
    columnStyles: {
      0: { cellWidth: 8, halign: "center" },
      1: { fontStyle: "bold", cellWidth: 42 },
      2: { cellWidth: 32 },
      3: { cellWidth: 35 },
      4: { cellWidth: 26, fontStyle: "bold" },
      5: { cellWidth: 20, halign: "center" },
      6: { cellWidth: 19, halign: "right", fontStyle: "bold" },
    },
    didParseCell: (data) => {
      if (data.section === "body" && data.column.index === 4) {
        const val = String(data.cell.raw);
        if (val === "Clocked In") {
          data.cell.styles.textColor = [5, 150, 105]; // Emerald
        } else if (val === "On Break") {
          data.cell.styles.textColor = [217, 119, 6]; // Amber
        } else {
          data.cell.styles.textColor = [148, 163, 184]; // Gray
        }
      }
    },
    margin: { left: 14, right: 14 },
  });

  // Footer notes & page numbering
  const pageCount = (doc as any).internal.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFont("helvetica", "italic");
    doc.setFontSize(7.5);
    doc.setTextColor(148, 163, 184);
    doc.text(
      "Mavis Strategic Partners (Pty) Ltd — Confidential Internal Operations Report",
      14,
      287
    );
    doc.text(`Page ${i} of ${pageCount}`, 196, 287, { align: "right" });
  }

  const safeDate = dateStr.replace(/[\s,]+/g, "_");
  doc.save(`MSP_Live_Presence_Report_${safeDate}.pdf`);
}

// 2. Export Weekly Attendance Register (Mon - Fri, 08:00 - 17:00)
export function exportAttendanceRegisterPdf(registerData: AttendanceRegisterData) {
  // Use Landscape orientation for clear, spacious 5-day Monday to Friday view
  const doc = new jsPDF({
    orientation: "landscape",
    unit: "mm",
    format: "a4",
  });

  const primaryColor = [15, 23, 42] as [number, number, number];
  const emeraldColor = [5, 150, 105] as [number, number, number];
  const mutedTextColor = [100, 116, 139] as [number, number, number];

  // Header Title
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.setTextColor(...primaryColor);
  doc.text("MAVIS STRATEGIC PARTNERS", 14, 15);

  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.setTextColor(...emeraldColor);
  doc.text("OFFICIAL ATTENDANCE REGISTER & WORKFORCE TIMESHEET", 14, 22);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(...mutedTextColor);
  doc.text(
    `Working Schedule: Monday to Friday, 08:00 – 17:00 (SAST) | Attendance Period: ${registerData.weekLabel}`,
    14,
    28
  );

  // Summary Metrics Banner (Landscape width = 297mm - 28mm margin = 269mm)
  doc.setFillColor(248, 250, 252);
  doc.setDrawColor(226, 232, 240);
  doc.roundedRect(14, 32, 269, 14, 2, 2, "FD");

  doc.setFontSize(7.5);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(...mutedTextColor);
  doc.text("TOTAL WORKFORCE", 20, 37);
  doc.text("AVERAGE PRESENCE RATE", 85, 37);
  doc.text("TOTAL LOGGED HOURS", 155, 37);
  doc.text("APPROVED LEAVE DAYS", 225, 37);

  doc.setFontSize(11);
  doc.setTextColor(...primaryColor);
  doc.text(`${registerData.stats.totalStaff} Team Members`, 20, 43);

  doc.setTextColor(5, 150, 105);
  doc.text(`${registerData.stats.avgAttendanceRate}%`, 85, 43);

  doc.setTextColor(...primaryColor);
  doc.text(`${registerData.stats.totalHoursLogged}`, 155, 43);

  doc.setTextColor(217, 119, 6);
  doc.text(`${registerData.stats.totalLeaveDays} Days`, 225, 43);

  // Days Header (Monday to Friday dates)
  const sampleDays = registerData.rows[0]?.days || [];
  const monHeader = sampleDays[0] ? `Mon (${sampleDays[0].formattedDate})\n08:00 - 17:00` : "Mon\n08:00-17:00";
  const tueHeader = sampleDays[1] ? `Tue (${sampleDays[1].formattedDate})\n08:00 - 17:00` : "Tue\n08:00-17:00";
  const wedHeader = sampleDays[2] ? `Wed (${sampleDays[2].formattedDate})\n08:00 - 17:00` : "Wed\n08:00-17:00";
  const thuHeader = sampleDays[3] ? `Thu (${sampleDays[3].formattedDate})\n08:00 - 17:00` : "Thu\n08:00-17:00";
  const friHeader = sampleDays[4] ? `Fri (${sampleDays[4].formattedDate})\n08:00 - 17:00` : "Fri\n08:00-17:00";

  // Build rows
  const tableData = registerData.rows.map((row, idx) => {
    const formatDayCell = (day?: AttendanceRegisterDay) => {
      if (!day) return "—";
      if (day.status === "Present") {
        const inTime = day.clockInTime || "08:00";
        const outTime = day.clockOutTime || "17:00";
        return `Present\n${inTime} - ${outTime}\n(${day.hoursWorked || "8h"})`;
      }
      if (day.status === "Approved Leave") {
        return `Approved Leave\n(HR Approved)\n${day.leaveReason || "Leave"}`;
      }
      if (day.status === "Did Not Clock In") {
        return `Did Not Clock In\n(Absent)\n0h 0m`;
      }
      return `Upcoming\n—`;
    };

    return [
      (idx + 1).toString(),
      `${row.name}\n${row.role}`,
      row.department,
      formatDayCell(row.days[0]),
      formatDayCell(row.days[1]),
      formatDayCell(row.days[2]),
      formatDayCell(row.days[3]),
      formatDayCell(row.days[4]),
      `${row.totalHoursWorked}\n(${row.daysPresent}/5 Days)`,
    ];
  });

  autoTable(doc, {
    startY: 50,
    head: [[
      "#",
      "Employee / Role",
      "Department",
      monHeader,
      tueHeader,
      wedHeader,
      thuHeader,
      friHeader,
      "Total Hours\n& Attendance",
    ]],
    body: tableData,
    theme: "grid",
    headStyles: {
      fillColor: primaryColor,
      textColor: [255, 255, 255],
      fontSize: 8,
      fontStyle: "bold",
      halign: "center",
      valign: "middle",
    },
    bodyStyles: {
      fontSize: 7.5,
      textColor: [30, 41, 59],
      cellPadding: 2,
      valign: "middle",
    },
    alternateRowStyles: {
      fillColor: [250, 250, 250],
    },
    columnStyles: {
      0: { cellWidth: 7, halign: "center" },
      1: { cellWidth: 42, fontStyle: "bold" },
      2: { cellWidth: 28 },
      3: { cellWidth: 38, halign: "center" },
      4: { cellWidth: 38, halign: "center" },
      5: { cellWidth: 38, halign: "center" },
      6: { cellWidth: 38, halign: "center" },
      7: { cellWidth: 38, halign: "center" },
      8: { cellWidth: 26, halign: "center", fontStyle: "bold" },
    },
    didParseCell: (data) => {
      // Color-code day cells (columns 3 through 7)
      if (data.section === "body" && data.column.index >= 3 && data.column.index <= 7) {
        const text = String(data.cell.raw);
        if (text.startsWith("Present")) {
          data.cell.styles.fillColor = [236, 253, 245]; // Emerald 50
          data.cell.styles.textColor = [6, 95, 70]; // Emerald 800
        } else if (text.startsWith("Approved Leave")) {
          data.cell.styles.fillColor = [254, 243, 199]; // Amber 100
          data.cell.styles.textColor = [146, 64, 14]; // Amber 800
        } else if (text.startsWith("Did Not Clock In")) {
          data.cell.styles.fillColor = [254, 242, 242]; // Rose 50
          data.cell.styles.textColor = [159, 18, 57]; // Rose 800
        } else {
          data.cell.styles.textColor = [148, 163, 184];
        }
      }
    },
    margin: { left: 14, right: 14 },
  });

  // Verification & Signatures section at bottom
  let finalY = (doc as any).lastAutoTable.finalY + 12;
  if (finalY > 175) {
    doc.addPage();
    finalY = 20;
  }

  doc.setFont("helvetica", "bold");
  doc.setFontSize(8.5);
  doc.setTextColor(...primaryColor);
  doc.text("AUTHORISATION & REGISTER SIGN-OFF", 14, finalY);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(7.5);
  doc.setTextColor(...mutedTextColor);
  doc.text("I hereby certify that this attendance register accurately reflects working hours from 08:00 to 17:00 (Mon–Fri) and approved HR leave.", 14, finalY + 5);

  const sigBoxY = finalY + 9;
  doc.setDrawColor(203, 213, 225);
  doc.line(14, sigBoxY + 8, 90, sigBoxY + 8);
  doc.text("Operations Manager Signature", 14, sigBoxY + 12);
  doc.text("Date: ________________________", 14, sigBoxY + 17);

  doc.line(110, sigBoxY + 8, 186, sigBoxY + 8);
  doc.text("Human Resources Department Signature", 110, sigBoxY + 12);
  doc.text("Date: ________________________", 110, sigBoxY + 17);

  doc.line(206, sigBoxY + 8, 282, sigBoxY + 8);
  doc.text("Managing Director / CEO Approval", 206, sigBoxY + 12);
  doc.text("Date: ________________________", 206, sigBoxY + 17);

  // Footer notes & page numbering
  const pageCount = (doc as any).internal.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFont("helvetica", "italic");
    doc.setFontSize(7);
    doc.setTextColor(148, 163, 184);
    doc.text(
      "Mavis Strategic Partners (Pty) Ltd — Official Attendance Register — Standard Shift: 08:00 - 17:00 SAST",
      14,
      202
    );
    doc.text(`Page ${i} of ${pageCount}`, 283, 202, { align: "right" });
  }

  const safeFilename = registerData.weekLabel.replace(/[\s,–—-]+/g, "_");
  doc.save(`MSP_Attendance_Register_${safeFilename}.pdf`);
}
